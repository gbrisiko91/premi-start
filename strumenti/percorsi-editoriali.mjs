export function selezionaRimando(articolo, candidati) {
  if (!articolo || articolo.bozza || !Array.isArray(candidati)) return null;
  const tags = new Set((articolo.tag || []).map(t => String(t).trim().toLowerCase()));
  if (tags.has("gta-6") && articolo.id !== "gta-6-guida-lancio") {
    const guida = candidati.find(a => a && a.id === "gta-6-guida-lancio" &&
      a.lingua === articolo.lingua && !a.bozza && a.url && a.url !== articolo.url);
    if (guida) return { tipo: "gta6", url: guida.url };
  }
  if (tags.has("indie")) return { tipo: "indie" };
  return null;
}
